class TestChunkGlossaryFilter:
    """Tests filter_glossary_for_chunk with regex word boundaries and case sensitivity."""

    def test_filter_exact_word_boundaries(self):
        """Matches whole words only, avoiding spurious substring matches."""
        glossary = [
            GlossaryItem(source_term="Cat", target_term="кіт", case_sensitive=False),
            GlossaryItem(source_term="Rabbitfolk", target_term="кролячий народ", case_sensitive=False),
            GlossaryItem(source_term="folk", target_term="народ", case_sensitive=False),
        ]
        
        # "Catch" contains "Cat" as substring, but word boundary \bCat\b must NOT match
        text1 = "They tried to catch the running dog."
        filtered1 = filter_glossary_for_chunk(glossary, text1)
        assert len(filtered1) == 0

        # "The Rabbitfolk lived here." matches "Rabbitfolk" and "folk" is not separate word unless present
        text2 = "The Rabbitfolk lived in peace."
        filtered2 = filter_glossary_for_chunk(glossary, text2)
        terms = [item.source_term for item in filtered2]
        assert "Rabbitfolk" in terms
        assert "Cat" not in terms

    def test_filter_case_sensitivity(self):
        """Respects item.case_sensitive flag."""
        glossary = [
            GlossaryItem(source_term="AI", target_term="ШІ", case_sensitive=True),
            GlossaryItem(source_term="apple", target_term="яблуко", case_sensitive=False),
        ]

        # Case sensitive 'AI' vs lowercase 'ai'
        text_lower = "The ai tool was fast."
        res_lower = filter_glossary_for_chunk(glossary, text_lower)
        assert "AI" not in [i.source_term for i in res_lower]

        text_upper = "The AI tool was fast."
        res_upper = filter_glossary_for_chunk(glossary, text_upper)
        assert "AI" in [i.source_term for i in res_upper]

        # Case insensitive 'apple' matches 'Apple'
        text_apple = "He ate an Apple."
        res_apple = filter_glossary_for_chunk(glossary, text_apple)
        assert "apple" in [i.source_term for i in res_apple]

    def test_filter_matches_in_source_or_draft(self):
        """Matches if term appears in either source text or draft translation."""
        glossary = [
            GlossaryItem(source_term="Sword", target_term="меч", case_sensitive=False),
            GlossaryItem(source_term="Shield", target_term="щит", case_sensitive=False),
        ]
        res = filter_glossary_for_chunk(glossary, chunk_text="He held a Sword.", draft_text="Він тримав Shield.")
        terms = [i.source_term for i in res]
        assert "Sword" in terms
        assert "Shield" in terms

    def test_filter_empty_inputs(self):
        """Handles empty glossary or empty text gracefully."""
        assert filter_glossary_for_chunk([], "Some text") == []
        assert filter_glossary_for_chunk([GlossaryItem(source_term="A", target_term="Б")], "") == []


