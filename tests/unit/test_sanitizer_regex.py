class TestSanitizerRegex:
    """Tests dynamic multi-pass regex sanitization in QuantizedAyaEditingEngine."""

    @pytest.fixture
    def engine(self):
        return QuantizedAyaEditingEngine(device="cpu", load_in_4bit=False)

    def test_sanitize_empty_and_whitespace_inputs(self, engine):
        """Sanitizer should return empty string for empty, None, or whitespace-only inputs."""
        assert engine._sanitize_output("") == ""
        assert engine._sanitize_output("   ") == ""
        assert engine._sanitize_output("\n\t  \n  ") == ""
        assert engine._sanitize_output(None) == ""

    def test_sanitize_markdown_code_fences(self, engine):
        """Strips markdown code fences (```markdown, ```ukrainian, ```, etc.)."""
        case1 = "```markdown\nЦе чистий переклад.\n```"
        assert engine._sanitize_output(case1) == "Це чистий переклад."

        case2 = "```ukrainian\nТекст без огорожі.\n```"
        assert engine._sanitize_output(case2) == "Текст без огорожі."

        case3 = "```\nПростий блок коду.\n```"
        assert engine._sanitize_output(case3) == "Простий блок коду."

        case4 = "```text\nБагаторядковий текст\nДругий рядок.\n```"
        assert engine._sanitize_output(case4) == "Багаторядковий текст\nДругий рядок."

    def test_sanitize_echoed_prompt_section_headers(self, engine):
        """Strips echoed prompt boundary headers like === SECTION ===."""
        case1 = "=== REFINED TRANSLATION ===\nЧистий переклад."
        assert engine._sanitize_output(case1) == "Чистий переклад."

        case2 = "=== ВІДРЕДАГОВАНИЙ ТЕКСТ ===\nТекст українською."
        assert engine._sanitize_output(case2) == "Текст українською."

        case3 = "==== ЧОРНОВИЙ ПЕРЕКЛАД ====\nВідновлений текст."
