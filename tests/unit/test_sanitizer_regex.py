    def test_sanitize_unmapped_inline_tags(self, engine):
        """Strips unmapped inline tag artifacts like <tag_1>, </tag_1>, <tag_12>."""
        case1 = "Текст <tag_1>з виділенням</tag_1> та <tag_12>іншими тегами</tag_12>."
        assert engine._sanitize_output(case1) == "Текст з виділенням та іншими тегами."

        case2 = "<tag_0>Початок речення</tag_0> і кінець."
        assert engine._sanitize_output(case2) == "Початок речення і кінець."

        case3 = "Слово <tag_999/> та ще одне."
        # Matches opening/closing tag patterns
        res = engine._sanitize_output("Слово <tag_99>іменник</tag_99>.")
        assert res == "Слово іменник."

    def test_sanitize_outer_wrapping_quotes(self, engine):
        """Strips wrapping quotation marks if they enclose the entire text without destroying internal dialogue quotes."""
        # Double quotes
        assert engine._sanitize_output('"Це ціле речення в лапках."') == "Це ціле речення в лапках."

        # Guillemets
        assert engine._sanitize_output('«Це ціле речення в ялинках.»') == "Це ціле речення в ялинках."

        # Curly quotes
        assert engine._sanitize_output('“Це ціле речення в фігурних лапках.”') == "Це ціле речення в фігурних лапках."

        # Single quotes
        assert engine._sanitize_output("'Це речення в одинарних лапках.'") == "Це речення в одинарних лапках."

        # Preserves internal dialogue quotes
        dialogue = '«Він сказав: "Ніколи!" і вийшов з кімнати.»'
        # Outer « » is stripped, internal " " is preserved
        sanitized = engine._sanitize_output(dialogue)
        assert sanitized == 'Він сказав: "Ніколи!" і вийшов з кімнати.'

    def test_sanitize_control_tokens(self, engine):
        """Strips arbitrary model control tokens (<|...|> like <|im_end|>, <|im_start|>, etc.)."""
        case1 = "<|im_start|>system\nТекст перекладу.<|im_end|>"
        assert engine._sanitize_output(case1) == "system\nТекст перекладу."

        case2 = "Речення з токеном кінця.<|endoftext|>"
        assert engine._sanitize_output(case2) == "Речення з токеном кінця."

        case3 = "<|START_OF_TURN_TOKEN|>Чистий текст.<|END_OF_TURN_TOKEN|>"
        assert engine._sanitize_output(case3) == "Чистий текст."

        case4 = "Текст <|custom_model_token_42|> всередині речення."
        assert engine._sanitize_output(case4) == "Текст  всередині речення."

    def test_sanitize_inline_markdown_emphasis(self, engine):
        """Strips inline bold (**...**) and italic (*...*) markdown formatting."""
        case1 = "Це було **неймовірно** гарне видовище."
        assert engine._sanitize_output(case1) == "Це було неймовірно гарне видовище."

        case2 = "Він промовив *пошепки*, щоб ніхто не почув."
        assert engine._sanitize_output(case2) == "Він промовив пошепки, щоб ніхто не почув."

        case3 = "Поєднання **жирного** та *курсивного* тексту."
        assert engine._sanitize_output(case3) == "Поєднання жирного та курсивного тексту."

    def test_sanitize_mixed_script_words_and_portmanteaus(self, engine):
        """Sanitizes mixed Cyrillic-Latin hybrid words and homoglyph leakages."""
        # Smachnissimo -> Smakota
        assert engine._sanitize_output("Це була справжня Смачнissimo страва!") == "Це була справжня Смакота страва!"
        assert engine._sanitize_output("Дуже смачнissimo вийшло.") == "Дуже смакота вийшло."

        # Garnissimo -> Pregarno
        assert engine._sanitize_output("Гарнissimo виглядає пейзаж.") == "Прегарно виглядає пейзаж."

        # Homoglyphs: 'мiсто' with Latin 'i' replaced with Cyrillic 'і'
        latin_i_word = "м" + "i" + "сто"  # Latin 'i'
        cleaned = engine._sanitize_output(latin_i_word)
        assert cleaned == "місто"
        assert "i" not in cleaned  # Latin i replaced

    def test_sanitize_multi_pass_layered_artifacts_convergence(self, engine):
        """Multi-pass loop converges when multiple layered artifacts are wrapped around text."""
        complex_artifact = (
            "```markdown\n"
            "# Фінальний покращений переклад:\n"
            "<|im_start|>assistant\n"
            "Ось готовий переклад:\n"
            "=== ВІДРЕДАГОВАНИЙ ТЕКСТ ===\n"
            '«<tag_1>**Чистий результат** після п\'яти проходів.</tag_1>»<|im_end|>\n'
            "```"
        )
        result = engine._sanitize_output(complex_artifact)
        assert result == "assistant\nЧистий результат після п'яти проходів." or result == "Чистий результат після п'яти проходів."


