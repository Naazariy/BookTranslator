class TestSegmenterLookahead:
    """Tests sentence boundary lookahead expansion in RuleBasedSegmenter."""

    def test_segmenter_starting_with_numbers(self):
        """Correctly splits sentences when the next sentence starts with digits."""
        text = "Розділ 1 закінчився. 1945 рік став початком нової епохи."
        sentences = RuleBasedSentenceSegmenter.split_sentences(text)
        assert len(sentences) == 2
        assert sentences[0] == "Розділ 1 закінчився."
        assert sentences[1] == "1945 рік став початком нової епохи."

        text2 = "Битва завершилася! 200 воїнів повернулися додому."
        sentences2 = RuleBasedSentenceSegmenter.split_sentences(text2)
        assert len(sentences2) == 2
        assert sentences2[0] == "Битва завершилася!"
        assert sentences2[1] == "200 воїнів повернулися додому."

    def test_segmenter_starting_with_inline_tags(self):
        """Correctly splits sentences when the next sentence starts with an XML/HTML tag."""
        text = "The first part was clear. <tag_1>The second part had special formatting.</tag_1>"
        sentences = RuleBasedSentenceSegmenter.split_sentences(text)
        assert len(sentences) == 2
        assert sentences[0] == "The first part was clear."
        assert sentences[1] == "<tag_1>The second part had special formatting.</tag_1>"

        text_uk = "Магічне закляття спрацювало! <bold>Темрява розсіялася над містом.</bold>"
        sentences_uk = RuleBasedSentenceSegmenter.split_sentences(text_uk)
        assert len(sentences_uk) == 2
        assert sentences_uk[0] == "Магічне закляття спрацювало!"
        assert sentences_uk[1] == "<bold>Темрява розсіялася над містом.</bold>"

    def test_segmenter_diverse_quotes_and_dialogue_dashes(self):
        """Correctly splits before dialogue dashes and quotation marks."""
        text = 'Перше речення закінчилося! — сказав він. «Друге речення почалося.»'
        sentences = RuleBasedSentenceSegmenter.split_sentences(text)
        # First sentence with dialogue attribution, second sentence with guillemets
        assert len(sentences) >= 2
        assert "«Друге речення почалося.»" in sentences[-1]

    def test_segmenter_abbreviations_and_honorifics(self):
        """Protects honorifics (Dr., Mr., St., м., вул.) while splitting real sentence boundaries."""
        text = "Dr. Watson met Mr. Holmes in London. They discussed the case."
        sentences = RuleBasedSentenceSegmenter.split_sentences(text)
        assert len(sentences) == 2
        assert sentences[0] == "Dr. Watson met Mr. Holmes in London."
        assert sentences[1] == "They discussed the case."

        text_uk = "м. Київ розташоване на р. Дніпро. Це красиве місто."
        sentences_uk = RuleBasedSentenceSegmenter.split_sentences(text_uk)
        assert len(sentences_uk) == 2
        assert sentences_uk[0] == "м. Київ розташоване на р. Дніпро."
        assert sentences_uk[1] == "Це красиве місто."

    def test_segmenter_terminal_abbreviations_with_lookahead(self):
        """Terminal abbreviations (etc., тощо) are protected mid-sentence but split at sentence ends."""
        text_split = "He brought apples, oranges, etc. Next, he prepared dinner."
        sentences = RuleBasedSentenceSegmenter.split_sentences(text_split)
        assert len(sentences) == 2
        assert sentences[0] == "He brought apples, oranges, etc."
        assert sentences[1] == "Next, he prepared dinner."


